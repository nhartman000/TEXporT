"""Render one or more capture sessions into the marked handoff document.

Same conventions as the Convo Markers browser extension:
  - reader instructions for the next AI
  - MARKED PASSAGES REGISTER (at the top, repeated at the end, because
    models attend best to the start and end of long inputs)
  - full text with [[MARK Mn START]] / [[MARK Mn END]] tags inline
"""
from __future__ import annotations

import html
from datetime import datetime


def tag(n, which: str) -> str:
    return f"[[MARK M{n} {which}]]"


def build(sessions: list[dict]) -> dict:
    """Number markers globally and resolve their text. Returns a doc model."""
    n = 0
    register = []
    out_sessions = []
    for si, s in enumerate(sessions):
        lines = s.get("lines", [])
        marks = sorted(s.get("markers", []), key=lambda m: m["start"])
        starts, ends = {}, {}
        numbered = []
        for m in marks:
            a, b = max(0, m["start"]), min(len(lines) - 1, m["end"])
            if a > b:
                continue
            n += 1
            mm = {"n": n, "start": a, "end": b, "note": (m.get("note") or "").strip()}
            numbered.append(mm)
            starts.setdefault(a, []).append(mm)
            ends.setdefault(b, []).append(mm)
            register.append({
                **mm, "si": si, "title": s.get("title") or f"Capture {si + 1}",
                "text": "\n".join(lines[i]["text"] for i in range(a, b + 1)),
            })
        out_sessions.append({**s, "_starts": starts, "_ends": ends, "_marks": numbered})
    return {"sessions": out_sessions, "register": register, "total": n}


def instructions(doc: dict) -> str:
    total = doc["total"]
    return (
        "READER INSTRUCTIONS — for any AI model processing this document\n\n"
        f"This document contains {len(doc['sessions'])} captured conversation(s), transcribed "
        "from the screen by OCR. Minor character-level OCR errors are possible; do not treat "
        f"odd characters as meaningful. The compiler marked {total} passage(s) as critical.\n\n"
        f"• Every marked passage is wrapped inline between {tag('n', 'START')} and "
        f"{tag('n', 'END')} (n = its ID).\n"
        "• Every marked passage is also reproduced in full in the MARKED PASSAGES REGISTER, "
        "at the start and again at the end of this document.\n\n"
        "Requirements:\n"
        "1. Read the entire document, not just the register.\n"
        "2. Treat every marked passage as high priority. Do not drop, compress, or paraphrase "
        "away its specifics (numbers, names, definitions, decisions, code, wording).\n"
        "3. When summarizing or answering, keep marked content verbatim where precision matters "
        "and cite it by ID (e.g. M3).\n"
        "4. If a marked passage conflicts with other content, flag the conflict instead of "
        "silently resolving it.\n"
        "5. Notes attached to a marker are the compiler's explanation of why it matters — "
        "follow them.\n"
        f"6. Before finishing any summary, confirm every ID M1–M{max(total, 1)} is accounted for."
    )


def _paragraphs(lines: list[dict]) -> list[list[int]]:
    paras: list[list[int]] = []
    for i, l in enumerate(lines):
        if not paras or l.get("par_break") or l.get("gap"):
            paras.append([i])
        else:
            paras[-1].append(i)
    return paras


def _reg_head(r: dict) -> str:
    span = f"line {r['start'] + 1}" if r["start"] == r["end"] else f"lines {r['start'] + 1}–{r['end'] + 1}"
    return f"M{r['n']} — Capture {r['si'] + 1} (“{r['title']}”), {span}"


def render_markdown(sessions: list[dict], title: str) -> str:
    doc = build(sessions)
    L = [f"# {title}", "",
         f"Compiled {datetime.now():%Y-%m-%d %H:%M} · {len(doc['sessions'])} capture(s) · {doc['total']} marker(s) · "
         "generated by TExporT (MG8-ready)", "",
         instructions(doc), "", "---", ""]

    def register(label):
        L.extend([f"## {label}", ""])
        if not doc["register"]:
            L.extend(["(no markers)", ""])
        for r in doc["register"]:
            L.append(f"### {_reg_head(r)}")
            if r["note"]:
                L.append(f"Note: {r['note']}")
            L.extend([tag(r["n"], "START"), r["text"], tag(r["n"], "END"), ""])

    register("MARKED PASSAGES REGISTER")
    for si, s in enumerate(doc["sessions"]):
        L.extend(["---", "", f"## CAPTURE {si + 1}: {s.get('title') or 'Untitled'}",
                  f"Source: {s.get('source', 'screen capture')} · captured {s.get('captured_at', '')[:16].replace('T', ' ')}", ""])
        lines = s.get("lines", [])
        for para in _paragraphs(lines):
            out = []
            for i in para:
                for m in s["_starts"].get(i, []):
                    out.append(tag(m["n"], "START") + (f" Note: {m['note']}" if m["note"] else ""))
                out.append(lines[i]["text"])
                for m in s["_ends"].get(i, []):
                    out.append(tag(m["n"], "END"))
            L.extend(out + [""])
    L.extend(["---", ""])
    register("MARKED PASSAGES REGISTER (repeated — verify every ID before finishing)")
    return "\n".join(L)


def render_html(sessions: list[dict], title: str) -> str:
    """Simple HTML that Qt's QTextDocument can print to PDF."""
    doc = build(sessions)
    e = html.escape
    H = ['<html><head><meta charset="utf-8"><style>',
         'body{font-family:"DejaVu Serif",Georgia,serif;font-size:10.5pt;color:#111;}',
         'h1{font-size:18pt;} h2{font-size:13pt;margin-top:18px;border-bottom:1px solid #111;}',
         '.meta{color:#555;font-size:9pt;} .inst{font-family:"DejaVu Sans",sans-serif;font-size:9pt;'
         'border:1px solid #111;padding:8px;white-space:pre-wrap;}',
         '.tag{font-family:"DejaVu Sans Mono",monospace;font-size:8.5pt;font-weight:bold;color:#92400e;}',
         '.reg{background:#fffbeb;padding:6px;margin:8px 0;} .rh{font-family:"DejaVu Sans",sans-serif;font-weight:bold;font-size:9pt;}',
         '.note{font-style:italic;font-size:9pt;} .m{background:#fde68a;} p{margin:0 0 8px 0;}',
         '.gap{color:#b91c1c;font-style:italic;}',
         '</style></head><body>',
         f'<h1>{e(title)}</h1>',
         f'<div class="meta">Compiled {datetime.now():%Y-%m-%d %H:%M} · {len(doc["sessions"])} capture(s) · {doc["total"]} marker(s)</div>',
         f'<pre class="inst">{e(instructions(doc))}</pre>']

    def register(label):
        H.append(f'<h2>{e(label)}</h2>')
        if not doc["register"]:
            H.append('<p>(no markers)</p>')
        for r in doc["register"]:
            H.append('<div class="reg">')
            H.append(f'<div class="rh">{e(_reg_head(r))}</div>')
            if r["note"]:
                H.append(f'<div class="note">Note: {e(r["note"])}</div>')
            H.append(f'<div class="tag">{e(tag(r["n"], "START"))}</div>')
            H.append('<div>' + "<br>".join(e(x) for x in r["text"].split("\n")) + '</div>')
            H.append(f'<div class="tag">{e(tag(r["n"], "END"))}</div></div>')

    register("MARKED PASSAGES REGISTER")
    for si, s in enumerate(doc["sessions"]):
        H.append(f'<h2>CAPTURE {si + 1}: {e(s.get("title") or "Untitled")}</h2>')
        H.append(f'<div class="meta">Source: {e(s.get("source", "screen capture"))} · captured '
                 f'{e(s.get("captured_at", "")[:16].replace("T", " "))}</div>')
        lines = s.get("lines", [])
        open_marks = 0
        for para in _paragraphs(lines):
            parts = []
            for i in para:
                for m in s["_starts"].get(i, []):
                    open_marks += 1
                    note = f' (Note: {e(m["note"])})' if m["note"] else ""
                    parts.append(f'<span class="tag">{e(tag(m["n"], "START"))}{note}</span>')
                cls = "gap" if lines[i].get("gap") else ("m" if open_marks else "")
                txt = e(lines[i]["text"])
                parts.append(f'<span class="{cls}">{txt}</span>' if cls else txt)
                for m in s["_ends"].get(i, []):
                    open_marks -= 1
                    parts.append(f'<span class="tag">{e(tag(m["n"], "END"))}</span>')
            H.append('<p>' + "<br>".join(parts) + '</p>')
    register("MARKED PASSAGES REGISTER (repeated — verify every ID before finishing)")
    H.append('</body></html>')
    return "\n".join(H)
